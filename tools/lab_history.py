"""Renders docs/benchmarks/lab-history.md: every lab experiment and the main line's wrong calls over time.

    python3 tools/lab_history.py [--ledger ledger.json] [--autolab state.json] [--eli5 eli5.json]

Without files it reads the tilawa-lab volume (/ledger.json, /autolab/state.json, /autolab/eli5.json) with
`modal volume get`. Numbers come straight from the ledger (tools/lab_ledger.py): practice wrong calls, and the
change an experiment's branch run made against the main-line score it was measured on. Test sets change over
time (lab-v1.4 -> lab-v1.5u), so numbers are comparable only within one test set.
"""
import argparse
import json
import subprocess
import sys
import tempfile
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import lab_ledger as L  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs/benchmarks/lab-history.md"
GH = "https://github.com/yazinsai/tilawa/commit/"


def volume(path: str) -> dict | None:
    with tempfile.TemporaryDirectory() as d:
        dst = Path(d, "f.json")
        p = subprocess.run(["modal", "volume", "get", "tilawa-lab", path, str(dst)], capture_output=True, text=True)
        return json.loads(dst.read_text()) if p.returncode == 0 else None


def load(arg: str | None, path: str) -> dict | None:
    return json.loads(Path(arg).read_text()) if arg else volume(path)


def cell(s: str, n: int = 160) -> str:
    s = " ".join((s or "").split()).replace("|", "\\|")
    return s if len(s) <= n else s[: n - 1].rstrip() + "…"


def sha(s: str | None) -> str:
    """A commit link; a run scored on an uncommitted tree (`<sha>-dirty`) links its base commit."""
    if not s:
        return ""
    base = s.removesuffix("-dirty")
    return f"[`{base[:8]}`]({GH}{base})" + (" (dirty)" if base != s else "")


def signed(n: int | None) -> str:
    return "" if n is None else f"{n:+d}"


def render(led: dict, auto: dict | None, eli5: dict) -> str:
    exps, main = led["experiments"], led["mainLine"]
    auto_x = (auto or {}).get("experiments", {})
    rows = []
    for id, e in exps.items():
        c = e["card"]
        r = next((r for r in reversed(e["results"]) if r["kind"] == "branch"), None)
        base = L.base_for(led, r) if r else None
        cmp = L.compare(r["practice"], base["practice"], c) if r and base else None
        state = e["state"]
        if state == "open" and id in auto_x and auto_x[id]["state"] != "open":
            state = f"open (autolab: {auto_x[id]['state']})"
        rows.append({"id": id, "c": c, "state": state, "r": r, "cmp": cmp, "e": e})
    rows.sort(key=lambda x: x["c"]["created"])

    out = ["# Lab history", "",
           "Every lab experiment (hand-run and autolab) and how the main line's wrong calls moved. Generated by "
           "`python3 tools/lab_history.py` from the lab ledger on the `tilawa-lab` volume; don't edit by hand. "
           "See `.scratch/lab/spec.md` for how experiments are scored.", "",
           f"Ledger test set now: `{led['testSet']}`. {len(exps)} experiments, {len(main)} main-line scores, "
           f"from {main[0]['at'][:10]} to {main[-1]['at'][:10]}. A change of {L.NOISE} or fewer wrong calls is noise.", ""]

    by_state = Counter(x["e"]["state"] for x in rows)
    by_author = Counter("autolab" if x["c"].get("author") == "autolab" else "hand" for x in rows)
    by_comp = Counter(x["c"]["component"] for x in rows)
    out += ["| | count |", "|---|---:|"]
    out += [f"| {k} | {v} |" for k, v in sorted(by_state.items())]
    out += [f"| {k} | {v} |" for k, v in sorted(by_author.items())]
    out += [f"| {k} | {v} |" for k, v in sorted(by_comp.items())]
    out += [f"| scored on practice | {sum(1 for x in rows if x['r'])} |", ""]

    out += ["## Main line over time", "",
            "Practice wrong calls (missed + false warnings) after each score of `main`. Lower is better. "
            "A new test set restarts the count.", ""]
    for ts in dict.fromkeys(m["testSet"] for m in main):
        pts = [m for m in main if m["testSet"] == ts]
        if len(pts) >= 3:
            out += ["```mermaid", "xychart-beta", f'    title "{ts}: practice wrong calls on main"',
                    f"    x-axis [{', '.join(str(i + 1) for i in range(len(pts)))}]",
                    '    y-axis "wrong calls" 0 --> ' + str(max(m["practice"]["wrongCalls"] for m in pts) + 5),
                    f"    line [{', '.join(str(m['practice']['wrongCalls']) for m in pts)}]", "```", ""]
    out += ["| # | date | test set | main | practice (missed / false) | exam | after | note |",
            "|---:|---|---|---|---|---:|---|---|"]
    for i, m in enumerate(main):
        p, x = m["practice"], m.get("exam")
        out.append(f"| {i + 1} | {m['at'][:10]} | {m['testSet']} | {sha(m['sha'])} | {p['wrongCalls']} ({p['missed']} / {p['falseWarnings']}) "
                   f"| {x['wrongCalls'] if x else ''} | {m.get('experiment') or ''} | {cell(m.get('note') or '', 120)} |")
    out.append("")

    out += ["## Folded experiments", "", "| date | experiment | component | by | practice change (overall / component) | fold |",
            "|---|---|---|---|---|---|"]
    for x in rows:
        if x["e"]["state"] != "folded":
            continue
        d, cmp, c = x["e"]["decision"] or {}, x["cmp"], x["c"]
        ch = f"{signed(cmp['overall']['change'])} / {signed(cmp[c['component']]['change'])}" if cmp else ""
        out.append(f"| {(d.get('at') or c['created'])[:10]} | {x['id']} | {c['component']} | {c.get('author', '')} | {ch} | {sha(d.get('sha'))} |")
    out.append("")

    out += ["## Every experiment", "",
            "Oldest first. *Expected* is the card's predicted change in overall wrong calls; *actual* is the branch run "
            "against the main line it was measured on. Each experiment's code is on `exp/<id>` (also pushed as "
            "`refs/lab/exp/<id>`, with main-line commits that later left `main` under `refs/lab/main/`: `git fetch origin 'refs/lab/*:refs/lab/*'`).", "",
            "| created | experiment | component | by | state | expected | actual | verdict | branch run | what it tried |",
            "|---|---|---|---|---|---:|---:|---|---|---|"]
    for x in rows:
        c, cmp, r = x["c"], x["cmp"], x["r"]
        what = eli5.get(x["id"]) or c["hypothesis"]
        out.append(f"| {c['created'][:10]} | {x['id']} | {c['component']} | {c.get('author', '')} | {x['state']} "
                   f"| {signed(c['expected']['overall'])} | {signed(cmp['overall']['change']) if cmp else ''} "
                   f"| {L.headline(cmp, c) if cmp else ''} | {sha(r['sha']) if r else ''} | {cell(what)} |")
    return "\n".join(out) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ledger"), ap.add_argument("--autolab"), ap.add_argument("--eli5")
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args()
    led = load(a.ledger, "/ledger.json")
    if not led:
        sys.exit("no ledger: pass --ledger or check `modal volume ls tilawa-lab /`")
    Path(a.out).write_text(render(led, load(a.autolab, "/autolab/state.json"), load(a.eli5, "/autolab/eli5.json") or {}))
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()

import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { DEFAULTS, loadReferenceIndex } from "../src/index.js";
import type { ReferenceAsset } from "../src/index.js";
import { syntheticFixture } from "./fixtures/synthetic.js";
import { runScenarios } from "./fixtures/parity/scenarios.js";
import type { ScenarioResult } from "./fixtures/parity/scenarios.js";
import { asset, tinyTilawa, wav } from "./helpers.js";

type Golden = { commit: string; results: Record<string, ScenarioResult> };
const readGolden = (name: string) => JSON.parse(readFileSync(new URL(`./fixtures/parity/${name}`, import.meta.url), "utf8")) as Golden;
// Generated by scripts/parity-golden.mjs from the research session at the pinned commit.
const golden = readGolden("golden.json");
// The same, generated at 1.0.0-rc.1's engine commit (8cb52cb4), before the refinements: with every refinement off, a
// session still gives rc.1's events.
const goldenRc1 = readGolden("golden-rc1.json");
const RC1_COMMIT = "8cb52cb4af3a6697d600a6f0292c86e17956a246";
const source = JSON.parse(readFileSync(new URL("../src/engine/SOURCE.json", import.meta.url), "utf8")) as { commit: string };
const plain = <T>(x: T): T => JSON.parse(JSON.stringify(x));
const V1_ONLY = ["sdkVersion", "modelSha256", "modelRelease", "tier", "backend"];
// Posterior probabilities are rounded to 4 decimals; ONNX float math differs slightly across CPUs (the golden is made
// on macOS, CI runs Linux), so a value can round either side. Everything else (events, mistakes, phonemes, ids) must
// match exactly; probabilities and phoneme confidences within PROB_TOL.
const PROB_TOL = 2e-4;
type Ev = { phonemes: { conf: number }[]; posteriors?: { probs: number[] } };
function sameEvidence(got: Ev[], want: Ev[], name: string) {
  const strip = (e: Ev[]) => e.map((x) => ({ ...x, phonemes: x.phonemes.map((p) => ({ ...p, conf: 0 })),
    ...(x.posteriors && { posteriors: { ...x.posteriors, probs: [] } }) }));
  expect(strip(got), name).toEqual(strip(want));
  got.forEach((g, i) => {
    g.phonemes.forEach((p, j) => expect(Math.abs(p.conf - want[i].phonemes[j].conf), `${name} conf`).toBeLessThanOrEqual(PROB_TOL));
    g.posteriors?.probs.forEach((v, j) => expect(Math.abs(v - want[i].posteriors!.probs[j]), `${name} probs`).toBeLessThanOrEqual(PROB_TOL));
  });
}
const researchView = (e: unknown) =>
  (e as { type: string }).type === "capabilities"
    ? Object.fromEntries(Object.entries(e as object).filter(([k]) => !V1_ONLY.includes(k)))
    : e;

describe("parity with the research session", () => {
  it("was generated from the vendored commit", () => {
    expect(golden.commit).toBe(source.commit);
  });

  const matches = async (golden: Golden, extra: object) => {
    const tilawa = await tinyTilawa({ recordEvidence: true });
    const index = loadReferenceIndex(asset<ReferenceAsset>("ref-v2.json"));
    const results = await runScenarios({
      start: (p, policy) => (p ? tilawa.startMemorization(p, { ...policy, ...extra }) : tilawa.startFreeRecitation({ ...policy, ...extra })) as never,
      wav: await wav(),
      index,
      synthetic: (spec) => syntheticFixture(index, spec as never).evidence,
    });
    expect(Object.keys(results)).toEqual(Object.keys(golden.results));
    for (const [name, want] of Object.entries(golden.results)) {
      const got = plain(results[name]);
      expect(got.returned, name).toEqual(want.returned);
      expect(got.subscribed.map(researchView), name).toEqual(want.subscribed);
      expect(got.mistakes, name).toEqual(want.mistakes);
      sameEvidence(got.evidence as never, want.evidence as never, name);
    }
    // The scenarios exercise the checker, not just the tracker.
    expect(golden.results["evidence-wrong-word-free"].mistakes).toHaveLength(1);
    await tilawa.dispose();
  };

  it("emits the same events, mistakes and evidence for the tiny model WAV and synthetic evidence", async () => {
    await matches(golden, {});
  });

  it("with every refinement off, emits 1.0.0-rc.1's events, mistakes and evidence", async () => {
    expect(goldenRc1.commit).toBe(RC1_COMMIT);
    await matches(goldenRc1, { refinements: Object.fromEntries(Object.keys(DEFAULTS.policy.refinements).map((k) => [k, false])) });
  });
});

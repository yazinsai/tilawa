/** Pack clean corpus replays into a text-indexed engine asset. Duplicate
 * contexts from one source collection count once, with their spelling union. */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { parseArgs } from "node:util";
import { loadReferenceIndex } from "../../core/src/reference.js";
import { seamTextKey, type SeamReplayAsset } from "../../core/src/seam-replay.js";

const { values } = parseArgs({ options: { bank: { type: "string" }, out: { type: "string" }, model: { type: "string" }, jobs: { type: "string" } } });
if (!values.bank || !values.out || !values.model || !values.jobs) throw new Error("--bank, --out, --model, --jobs required");
const index = loadReferenceIndex(JSON.parse(readFileSync(new URL("../../core/assets/ref-v2.json", import.meta.url), "utf8")));
const manifest = JSON.parse(readFileSync(`${values.model}/manifest.json`, "utf8"));
const jobs = JSON.parse(readFileSync(values.jobs, "utf8"));
const cells = new Map<string, Map<string, Set<string>>>();
const files = readdirSync(values.bank).filter(f => f.endsWith(".json"));
if (files.length !== jobs.length) throw new Error(`Incomplete bank: ${files.length}/${jobs.length} recordings`);
let source: string | undefined;
for (let ji = 0; ji < jobs.length; ji++) {
  const file = `${ji}.json`, job = jobs[ji];
  const part = JSON.parse(readFileSync(`${values.bank}/${file}`, "utf8"));
  if (part.reference !== index.version || part.inventory !== index.inventoryId || part.model !== manifest.sha256)
    throw new Error(`Incompatible replay ${file}`);
  if (typeof part.reader !== "string" || !part.reader) throw new Error(`Missing source collection in ${file}`);
  if (part.reader !== job.reader || part.context !== job.location || typeof part.source !== "string" || !part.source)
    throw new Error(`Wrong recording in ${file}`);
  source ??= part.source;
  if (source !== part.source) throw new Error(`Mixed builder versions in ${file}`);
  const wanted = new Set<number>(job.seams);
  for (const seam of part.seams) {
    if (!wanted.has(seam.word)) throw new Error(`Unexpected seam in ${file}`);
    if (seam.key !== seamTextKey(index, seam.word) || !seam.key) throw new Error(`Invalid text key in ${file}`);
    if (!cells.has(seam.key)) cells.set(seam.key, new Map());
    const readers = cells.get(seam.key)!;
    if (!readers.has(part.reader)) readers.set(part.reader, new Set());
    for (const word of seam.words) {
      if (typeof word !== "string" || !word) throw new Error(`Invalid spelling in ${file}`);
      readers.get(part.reader)!.add(word);
    }
  }
}
const asset: SeamReplayAsset = { reference: index.version, inventory: index.inventoryId, seams: {} };
for (const [key, readers] of [...cells].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) {
  asset.seams[key] = { replays: readers.size, words: [...new Set([...readers.values()].flatMap(w => [...w]))].sort() };
}
writeFileSync(values.out, `// Generated by seam-replay-pack.ts from clean corpus replays.\n` +
  `// Builder source: ${source}; listener: ${manifest.sha256}.\n` +
  `import type { SeamReplayAsset } from "./seam-replay.js";\n` +
  `export const SEAM_REPLAYS: SeamReplayAsset = ${JSON.stringify(asset)};\n`);
console.log(JSON.stringify({ recordings: jobs.length, source, seams: cells.size, covered: Object.values(asset.seams).filter(s => s.replays >= 2).length,
  model: manifest.sha256 }));
